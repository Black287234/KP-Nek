def new_doc(landscape=False):
    d = Document()
    st = d.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(12)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    s = d.sections[0]
    if landscape:
        s.orientation = WD_ORIENT.LANDSCAPE
        s.page_width, s.page_height = s.page_height, s.page_width
    s.left_margin, s.right_margin, s.top_margin, s.bottom_margin = Cm(2.5), Cm(1.5), Cm(1.5), Cm(1.5)
    for name in ("Heading 1", "Heading 2"):
        h = d.styles[name]
        h.font.name = "Times New Roman"
        h.font.color.rgb = None
        h.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    d.styles["Heading 1"].font.size = Pt(15)
    d.styles["Heading 2"].font.size = Pt(13)
    return d


def head(d, text, level=1):
    h = d.add_heading(text, level)
    for r in h.runs:
        r.font.name = "Times New Roman"
    return h


def para(d, text, bold_prefix=None, size=12):
    p = d.add_paragraph()
    if bold_prefix:
        r = p.add_run(bold_prefix)
        r.bold = True
        r.font.size = Pt(size)
    r = p.add_run(text)
    r.font.size = Pt(size)
    p.paragraph_format.space_after = Pt(4)
    return p


def bullets(d, items, numbered=False):
    for t in items:
        p = d.add_paragraph(t, style="List Number" if numbered else "List Bullet")
        p.paragraph_format.space_after = Pt(2)


def code(d, text):
    p = d.add_paragraph()
    r = p.add_run(text)
    r.font.name = "Consolas"
    r.font.size = Pt(10.5)
    p.paragraph_format.left_indent = Cm(0.7)


def table(d, rows, widths, size=10, header=True):
    t = d.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    t.autofit = False
    for j, w in enumerate(widths):
        t.columns[j].width = Cm(w)
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            c = t.cell(i, j)
            c.text = str(v)
            c.width = Cm(widths[j])
            for p in c.paragraphs:
                p.paragraph_format.space_after = Pt(0)
                for r in p.runs:
                    r.font.size = Pt(size)
                    r.bold = header and i == 0
    if header:  # повтор заголовка таблицы на каждой странице
        tr_pr = t.rows[0]._tr.get_or_add_trPr()
        el = OxmlElement("w:tblHeader")
        el.set(qn("w:val"), "true")
        tr_pr.append(el)
    d.add_paragraph()
    return t


def caption(d, text):
    p = d.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(12)
    p.paragraph_format.space_after = Pt(2)


def fact(key):
    return str(R[key]).replace("\n", " ")


